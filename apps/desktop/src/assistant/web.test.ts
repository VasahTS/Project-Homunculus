import { readFileSync } from "node:fs";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { isBotCheck, nativeWeb, parseResults, readable, WebLimitedError, WebQueue, WebSession, type GetPage, type SearchPage, type WebTransport } from "./web.ts";
const html = readFileSync(new URL("./fixtures/search.html", import.meta.url), "utf8");
const pageHtml = readFileSync(new URL("./fixtures/page.html", import.meta.url), "utf8");
const ok = (body = html, status = 200): SearchPage => ({ status, html: body });
const page = (body = pageHtml): GetPage => ({ status: 200, finalUrl: "https://example.org/page", contentType: "text/html; charset=utf-8", body, cut: false });
function setup(queue = new WebQueue()) {
  const searchPage = vi.fn<WebTransport["searchPage"]>().mockResolvedValue(ok());
  const get = vi.fn<WebTransport["get"]>().mockResolvedValue(page());
  return { searchPage, get, session: new WebSession({ searchPage, get }, queue), queue };
}
async function advance<T>(promise: Promise<T>, ms = 0): Promise<T> {
  const observed = promise.then((value) => ({ value }), (error: unknown) => ({ error }));
  await vi.advanceTimersByTimeAsync(ms);
  const result = await observed;
  if ("error" in result) throw result.error;
  return result.value;
}
const deferred = <T,>() => { let resolve!: (value: T) => void; const promise = new Promise<T>((r) => { resolve = r; }); return { promise, resolve }; };
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(0); });
afterEach(() => { vi.useRealTimers(); });

describe("DuckDuckGo parsing", () => {
  it("matches expected values generated by the original pinned Flint functions", () => {
    const original = JSON.parse(readFileSync(new URL("./fixtures/flint-parity.json", import.meta.url), "utf8"));
    expect(parseResults(original.html)).toEqual(original.results);
  });
  it("keeps organic order, accents, entities, direct/uddg links; skips ads, duplicates and non-web links", () => {
    expect(parseResults(html)).toEqual([
      { title: "Cânon & 世界", url: "https://example.org/canon?a=1&b=2", snippet: 'A short "source" é 世.' },
      { title: "Rules", url: "https://second.example/rules", snippet: "Some rules." },
      { title: "https://empty.example/", url: "https://empty.example/", snippet: "" },
    ]);
  });
  it("bounds title and snippet, and treats no results as an empty list", () => {
    expect(parseResults("<html>No matches</html>")).toEqual([]);
    const [r] = parseResults(`<div class="result organic"><a class="result__a" href="https://example.org">${"T".repeat(200)}</a><p class="result__snippet">${"S".repeat(500)}</p></div>`);
    expect(r!.title).toHaveLength(120); expect(r!.snippet).toHaveLength(300);
  });
  it("does not invent a destination for an empty href or a relative non-redirect", () => {
    expect(parseResults('<div class="result organic"><a class="result__a" href="">Empty</a></div>')).toEqual([]);
  });
  it("encodes non-English queries without leaking any unrelated context", async () => {
    const { session, searchPage } = setup();
    const result = await advance(session.search("  São   Paulo 世界 & rules  "));
    expect(new URLSearchParams(searchPage.mock.calls[0]![0]).get("q")).toBe("São Paulo 世界 & rules");
    expect([...new URLSearchParams(searchPage.mock.calls[0]![0]).keys()]).toEqual(["q"]);
    expect(result.results[0]!.title).toBe("Cânon & 世界");
  });
  it("limits results to 5 by default and 10 at most without caching a count-specific subset", async () => {
    const { session, searchPage } = setup();
    searchPage.mockResolvedValue(ok(Array.from({ length: 12 }, (_, i) => `<div class="result organic"><a class="result__a" href="https://example.org/${i}">${i}</a></div>`).join("")));
    expect((await advance(session.search("many"))).results).toHaveLength(5);
    expect((await advance(session.search("many", 100))).results).toHaveLength(10);
    expect(searchPage).toHaveBeenCalledTimes(1);
  });
  it.each(["anomaly-modal", "challenge-form"])("recognizes %s", (marker) => { expect(isBotCheck(marker)).toBe(true); });
});

describe("readable pages", () => {
  it("keeps the title, headings and link text, drops non-content blocks and comments", () => {
    const result = readable(pageHtml, "text/html; charset=UTF-8");
    expect(result.title).toBe("Readable & clear");
    expect(result.text).toBe("# A heading\n\nVisible & useful link text.\n\n## 世界\n\nSecond é paragraph.");
    expect(result.text).not.toContain("hidden");
  });
  it.each(["text/plain", "text/markdown", "application/json", "application/ld+json"])("leaves %s unchanged", (type) => {
    const text = '  <script>as data</script>\n{"value": "&amp;"}\n';
    expect(readable(text, type)).toEqual({ title: "", text });
  });
  it.each(["application/pdf", "image/png", "application/octet-stream"])("refuses %s", (type) => {
    expect(() => readable("binary", type)).toThrow(`Can't read ${type} pages yet.`);
  });
  it("does not expose an unfinished script from a capped HTML body", () => {
    expect(readable("<p>Shown</p><script>never returned", "text/html").text).toBe("Shown");
  });
});

describe("shared queue and cancellation", () => {
  it("serializes searches from separate sessions, at least 2 seconds apart", async () => {
    const queue = new WebQueue(); const a = setup(queue); const b = setup(queue);
    const times: number[] = []; let active = 0; let max = 0;
    const transport = async () => { times.push(Date.now()); max = Math.max(max, ++active); await new Promise((r) => setTimeout(r, 2500)); active--; return ok(); };
    a.searchPage.mockImplementation(transport); b.searchPage.mockImplementation(transport);
    const first = a.session.search("first"); const second = b.session.search("second");
    await advance(Promise.all([first, second]), 5000);
    expect(max).toBe(1); expect(times).toEqual([0, 2500]);
    await advance(a.session.search("third"), 2500);
  });
  it("paces quick searches by 2 seconds", async () => {
    const { session, searchPage } = setup(); const times: number[] = [];
    searchPage.mockImplementation(async () => { times.push(Date.now()); return ok(); });
    await advance(Promise.all([session.search("one"), session.search("two")]), 2000);
    expect(times).toEqual([0, 2000]);
  });
  it("allows at most two unpaced page requests", async () => {
    const { session, get } = setup(); const pending = deferred<GetPage>();
    get.mockReturnValue(pending.promise);
    const all = Promise.all([1, 2, 3].map((i) => session.fetch(`https://example.org/${i}`)));
    await vi.advanceTimersByTimeAsync(0); expect(get).toHaveBeenCalledTimes(2);
    pending.resolve(page()); await all; expect(get).toHaveBeenCalledTimes(3);
  });
  it.each(["search", "fetch"] as const)("stops an in-flight %s immediately, ignores its late answer, and holds its native slot", async (kind) => {
    const { session, searchPage, get } = setup(); const controller = new AbortController();
    const searchPending = deferred<SearchPage>(); const pagePending = deferred<GetPage>();
    searchPage.mockReturnValue(searchPending.promise); get.mockReturnValue(pagePending.promise);
    const request = kind === "search" ? session.search("one", 5, { signal: controller.signal }) : session.fetch("https://example.org/", { signal: controller.signal });
    const assertion = expect(request).rejects.toThrow("Stopped.");
    await vi.advanceTimersByTimeAsync(0); controller.abort(); await assertion;
    if (kind === "search") {
      searchPage.mockResolvedValue(ok()); const next = session.search("two");
      await vi.advanceTimersByTimeAsync(5000); expect(searchPage).toHaveBeenCalledTimes(1);
      searchPending.resolve(ok()); await advance(next);
      expect(searchPage).toHaveBeenCalledTimes(2);
    } else { pagePending.resolve(page()); await vi.advanceTimersByTimeAsync(0); }
  });
  it("aborts a queued search before it reaches the transport", async () => {
    const { session, searchPage } = setup(); const pending = deferred<SearchPage>(); searchPage.mockReturnValueOnce(pending.promise);
    const first = session.search("one"); const controller = new AbortController();
    const assertion = expect(session.search("two", 5, { signal: controller.signal })).rejects.toThrow("Stopped.");
    controller.abort(); await assertion; pending.resolve(ok()); await advance(first); await vi.advanceTimersByTimeAsync(3000);
    expect(searchPage).toHaveBeenCalledTimes(1);
  });
});

describe("throttling, retries and cooldown", () => {
  it.each([200, 202, 403])("checks bot pages before HTTP %s", async (status) => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValue(ok('<form id="challenge-form">', status));
    await expect(advance(session.search("query"))).rejects.toThrow("DuckDuckGo is limiting searches right now (bot check). Try again in about 30 s; don't search again before then.");
    expect(searchPage).toHaveBeenCalledTimes(1);
  });
  it.each([202, 403, 429])("treats HTTP %s as limited without a bot marker", async (status) => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValue(ok("", status));
    await expect(advance(session.search("query"))).rejects.toThrow(`(HTTP ${status})`);
  });
  it("uses Retry-After capped at 5 minutes and sends nothing during longer cooldowns", async () => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValue({ ...ok("", 429), retryAfterSecs: 900 });
    await expect(advance(session.search("one"))).rejects.toMatchObject({ seconds: 300 });
    const onWait = vi.fn();
    await expect(advance(session.search("two", 5, { onWait }))).rejects.toMatchObject({ seconds: 300 });
    expect(onWait).not.toHaveBeenCalled(); expect(searchPage).toHaveBeenCalledTimes(1);
  });
  it("waits automatically for a cooldown of at most 30 seconds", async () => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValueOnce(ok("", 429));
    await expect(advance(session.search("one"))).rejects.toBeInstanceOf(WebLimitedError);
    const onWait = vi.fn(); const next = session.search("two", 5, { onWait });
    await vi.advanceTimersByTimeAsync(29_999); expect(onWait).toHaveBeenCalledWith(30); expect(searchPage).toHaveBeenCalledTimes(1);
    await advance(next, 1); expect(searchPage).toHaveBeenCalledTimes(2);
  });
  it("ends a cooldown wait immediately on Stop", async () => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValueOnce(ok("", 202));
    await expect(advance(session.search("one"))).rejects.toBeInstanceOf(WebLimitedError);
    const controller = new AbortController(); const onWait = vi.fn();
    const next = session.search("two", 5, { signal: controller.signal, onWait }); const assertion = expect(next).rejects.toThrow("Stopped.");
    await vi.advanceTimersByTimeAsync(0); expect(onWait).toHaveBeenCalledWith(30);
    controller.abort(); await assertion; await vi.advanceTimersByTimeAsync(60_000); expect(searchPage).toHaveBeenCalledTimes(1);
  });
  it("increases cooldown 30 → 60 → 120 → 300 and resets after 10 quiet minutes", async () => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValue(ok("", 429));
    for (const seconds of [30, 60, 120, 300]) {
      await expect(advance(session.search(`strike ${seconds}`))).rejects.toMatchObject({ seconds });
      await vi.advanceTimersByTimeAsync(seconds * 1000);
    }
    await vi.advanceTimersByTimeAsync(600_000);
    await expect(advance(session.search("reset"))).rejects.toMatchObject({ seconds: 30 });
  });
  it("retries a search 404 only once, 3 seconds later, then reports the actual status", async () => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValue(ok("", 404));
    const request = session.search("missing"); const assertion = expect(request).rejects.toThrow("DuckDuckGo answered HTTP 404.");
    await vi.advanceTimersByTimeAsync(2999); expect(searchPage).toHaveBeenCalledTimes(1);
    await vi.advanceTimersByTimeAsync(1); await assertion; expect(searchPage).toHaveBeenCalledTimes(2);
  });
  it("accepts a successful retry and never retries a transport error automatically", async () => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValueOnce(ok("", 500));
    expect((await advance(session.search("temporary"), 3000)).results).toHaveLength(3);
    searchPage.mockRejectedValueOnce(new Error("DuckDuckGo did not answer in time."));
    await expect(advance(session.search("timeout"), 2000)).rejects.toThrow("did not answer in time");
    expect(searchPage).toHaveBeenCalledTimes(3);
  });
});

describe("session caches and page outcomes", () => {
  it("normalizes duplicate queries, caches empty answers too, expires at ten minutes", async () => {
    const { session, searchPage } = setup(); searchPage.mockResolvedValue(ok("No results"));
    const [a, b] = await advance(Promise.all([session.search(" A   QUERY "), session.search("a query")]));
    expect(a.cached).toBe(false); expect(b.cached).toBe(true); expect(b.note).toBe("(from a moment ago)"); expect(searchPage).toHaveBeenCalledTimes(1);
    await vi.advanceTimersByTimeAsync(600_000); expect((await advance(session.search("a query"))).cached).toBe(false);
    expect(searchPage).toHaveBeenCalledTimes(2);
  });
  it("evicts the oldest search entry at 50 and keeps caches per session", async () => {
    const { session, searchPage, queue } = setup();
    for (let i = 0; i < 51; i++) await advance(session.search(`query ${i}`), 2000);
    expect((await advance(session.search("query 1"))).cached).toBe(true);
    expect((await advance(session.search("query 0"), 2000)).cached).toBe(false);
    expect(searchPage).toHaveBeenCalledTimes(52);
    const other = setup(queue); expect((await advance(other.session.search("query 1"), 2000)).cached).toBe(false);
  });
  it("caches readable text by normalized URL and preserves native cap metadata", async () => {
    const { session, get } = setup(); get.mockResolvedValue({ ...page("x".repeat(100_000)), contentType: "text/plain", cut: true });
    const a = await session.fetch("https://example.org/page#top"); const b = await session.fetch("https://example.org/page");
    expect(a.text).toHaveLength(100_000); expect(a.cut).toBe(true); expect(b.cached).toBe(true); expect(b.note).toBe("(from a moment ago)");
    expect(get).toHaveBeenCalledTimes(1); await vi.advanceTimersByTimeAsync(600_000);
    expect((await session.fetch("https://example.org/page")).cached).toBe(false);
  });
  it("evicts the oldest page at 50", async () => {
    const { session, get } = setup();
    for (let i = 0; i < 51; i++) await session.fetch(`https://example.org/${i}`);
    expect((await session.fetch("https://example.org/1")).cached).toBe(true);
    expect((await session.fetch("https://example.org/0")).cached).toBe(false); expect(get).toHaveBeenCalledTimes(52);
  });
  it("returns a cross-host redirect without reading the other host", async () => {
    const { session, get } = setup(); get.mockResolvedValue({ ...page(), status: 302, redirectTo: "https://other.example/page" });
    await expect(session.fetch("https://example.org/page")).rejects.toThrow("https://example.org/page redirects to https://other.example/page. It was not followed; call web_fetch with that address if you want it.");
    expect(get).toHaveBeenCalledTimes(1);
  });
  it("reports page status and does not retry or cache a failed page", async () => {
    const { session, get } = setup(); get.mockResolvedValueOnce({ ...page(), status: 404 });
    await expect(session.fetch("https://example.org/page")).rejects.toThrow("example.org answered HTTP 404.");
    expect((await session.fetch("https://example.org/page")).cached).toBe(false); expect(get).toHaveBeenCalledTimes(2);
  });
  it.each(["file:///secret", "http://example.org:8080/", "https://user:password@example.org/"])("refuses %s before transport", async (url) => {
    const { session, get } = setup(); await expect(session.fetch(url)).rejects.toThrow("That address is on this computer or a private network, so it can't be read."); expect(get).not.toHaveBeenCalled();
  });
  it("coalesces concurrent reads of a page without coupling the callers' Stop signals", async () => {
    const { session, get } = setup(); const pending = deferred<GetPage>(); get.mockReturnValue(pending.promise);
    const controller = new AbortController();
    const aborted = session.fetch("https://example.org/page", { signal: controller.signal }); const assertion = expect(aborted).rejects.toThrow("Stopped.");
    const next = session.fetch("https://example.org/page"); await vi.advanceTimersByTimeAsync(0);
    expect(get).toHaveBeenCalledTimes(1); controller.abort(); await assertion; pending.resolve(page());
    expect((await next).title).toBe("Readable & clear");
    expect((await session.fetch("https://example.org/page")).cached).toBe(true);
  });
  it("shares a provider cooldown between chats", async () => {
    const queue = new WebQueue(); const a = setup(queue); const b = setup(queue);
    a.searchPage.mockResolvedValue({ ...ok("", 429), retryAfterSecs: 60 });
    await expect(advance(a.session.search("one"))).rejects.toMatchObject({ seconds: 60 });
    await expect(advance(b.session.search("two"))).rejects.toMatchObject({ seconds: 60 });
    expect(b.searchPage).not.toHaveBeenCalled();
  });  it("gives the desktop-only error in the browser preview for both commands", async () => {
    await expect(nativeWeb.searchPage("q=test")).rejects.toThrow("Web search works in the desktop app only.");
    await expect(nativeWeb.get("https://example.org/")).rejects.toThrow("Web search works in the desktop app only.");
  });
});
